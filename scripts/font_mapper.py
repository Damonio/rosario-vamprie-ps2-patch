# Build reverse lookup preferring first occurrence (full-width for JP, half-width for ASCII)
CHAR_TO_GLYPH_FW: Dict[str, int] = {}
for _code, _ch in GLYPH_TO_CHAR.items():
    if _code >= 0x8080 and _ch not in CHAR_TO_GLYPH_FW:
        CHAR_TO_GLYPH_FW[_ch] = _code

# Standard punctuation aliases for full-width mode
CHAR_TO_GLYPH_FW.setdefault("、", 0x812C)
CHAR_TO_GLYPH_FW.setdefault("！", 0x8121)
CHAR_TO_GLYPH_FW.setdefault("？", 0x8202)
CHAR_TO_GLYPH_FW.setdefault("（", 0x8128)
CHAR_TO_GLYPH_FW.setdefault("）", 0x8129)

_TAG_RE = re.compile(r"\[(C:\d+|RUBY|G:[0-9A-Fa-f]{4}|B:[0-9A-Fa-f]{2})\]")


def decode_game_string(raw: bytes, lossless: bool = False) -> str:
    """
    Decodes a null-terminated (or raw slice) custom-encoded byte string from .evb or SLPM_551.89.
    If lossless=True, any duplicate/unmapped glyph is emitted as [G:XXXX] so re-encoding is bit-exact.
    """
    out: List[str] = []
    p = 0
    n = len(raw)
    while p < n and raw[p] != 0:
        b = raw[p]
        if b == 0x0A:
            out.append("\n")
            p += 1
        elif b == 0x1E and p + 1 < n:
            out.append(f"[C:{raw[p + 1]}]")
            p += 2
        elif b == 0x1F:
            out.append("[RUBY]")
            p += 1
        elif b == 0x20:
            out.append(" ")
            p += 1
        elif (b & 0x80) and p + 1 < n:
            code = (b << 8) | raw[p + 1]
            ch = GLYPH_TO_CHAR.get(code)
            if ch is not None and (not lossless or CHAR_TO_GLYPH_FW.get(ch) == code or 0x8020 <= code <= 0x807E):
                out.append(ch)
            else:
                out.append(f"[G:{code:04X}]")
            p += 2
        else:
            out.append(f"[B:{b:02X}]")
            p += 1
    return "".join(out)


def wrap_english_text(text: str, max_cols: int = 34, max_lines: int = 3) -> str:
    """
    Automatically word-wraps English dialogue to fit the PS2 message bubble.
    The PS2 text box fits ~32-36 half-width characters per line (10px glyphs in fn011.fnt)
    and up to 3 lines.
    Strips legacy [RUBY] tags and wraps words across lines.
    """
    # Replace [RUBY] tags with clean spacing
    text = re.sub(r"\[RUBY\]", " ", text)
    text = re.sub(r" +", " ", text)

    # Check if all existing lines already fit within max_cols
    existing_lines = text.split("\n")
    if all(len(_TAG_RE.sub("", l).strip()) <= max_cols for l in existing_lines) and len(existing_lines) <= max_lines:
        return text

    # Split into words across lines while preserving punctuation
    all_words = []
    for l in existing_lines:
        l = l.strip()
        if l:
            all_words.extend(l.split())

    if not all_words:
        return text

    lines_out: List[str] = []
    curr_line = ""
    for w in all_words:
        vis_w = _TAG_RE.sub("", w)
        vis_curr = _TAG_RE.sub("", curr_line)
        if not curr_line:
            curr_line = w
        elif len(vis_curr) + 1 + len(vis_w) <= max_cols:
            curr_line += " " + w
        else:
            lines_out.append(curr_line)
            curr_line = w
    if curr_line:
        lines_out.append(curr_line)

    # If lines_out exceeds max_lines, greedily merge lines up to max_cols + 6
    if len(lines_out) > max_lines:
        merged = []
        for line in lines_out:
            if merged and len(merged) == max_lines:
                merged[-1] += " " + line
            elif merged and len(_TAG_RE.sub("", merged[-1])) + 1 + len(_TAG_RE.sub("", line)) <= max_cols + 6:
                merged[-1] += " " + line
            else:
                merged.append(line)
        lines_out = merged

    return "\n".join(lines_out)


def encode_game_string(text: str, use_halfwidth_ascii: bool = True, auto_wrap: bool = False, max_cols: int = 34,
                       compact_spaces: bool = False) -> bytes:
    """
    Encodes a UTF-8 string into the game's custom 16-bit big-endian font encoding.
    - When use_halfwidth_ascii=True (default for English translations):
      ASCII 0x21..0x7E are encoded as 0x8021..0x807E (10px half-width in fn011.fnt),
      and ASCII space " " is encoded as 0x8020 (half-width glyph).
    - When compact_spaces=True, ASCII space is emitted as the single raw byte 0x20 instead
      (the original .evb scripts use this form too, e.g. e104550.evb), saving 1 byte per space.
      Use it for variable-length script text, never for fixed 2-byte-per-glyph tables.
    - Control tags [C:n], [RUBY], [G:XXXX], [B:XX] are restored to their exact byte sequences.
    """
    if auto_wrap:
        text = wrap_english_text(text, max_cols=max_cols)

    # Normalize curly quotes/dashes for clean English rendering
    if use_halfwidth_ascii:
        text = (
            text.replace("’", "'")
            .replace("‘", "'")
            .replace("“", '"')
            .replace("”", '"')
            .replace("—", "-")
            .replace("–", "-")
            .replace("…", "...")
            .replace("é", "e")
            .replace("è", "e")
            .replace("ê", "e")
            .replace("á", "a")
            .replace("à", "a")
            .replace("í", "i")
            .replace("ó", "o")
            .replace("ú", "u")
            .replace("ñ", "n")
            .replace("¡", "!")
            .replace("¿", "?")
        )

    out = bytearray()
    pos = 0
    n = len(text)
    while pos < n:
        if text[pos] == "[":
            m = _TAG_RE.match(text, pos)
            if m:
                tag = m.group(1)
                if tag == "RUBY":
                    out.append(0x1F)
                elif tag.startswith("C:"):
                    out.append(0x1E)
                    out.append(int(tag[2:]) & 0xFF)
                elif tag.startswith("G:"):
                    code = int(tag[2:], 16)
                    out.append((code >> 8) & 0xFF)
                    out.append(code & 0xFF)
                elif tag.startswith("B:"):
                    out.append(int(tag[2:], 16) & 0xFF)
                pos = m.end()
                continue

        ch = text[pos]
        pos += 1
        if ch == "\r":
            continue
        if ch == "\n":
            out.append(0x0A)
            continue
        if ch == " " and compact_spaces:
            out.append(0x20)
            continue
        if ch == " " and use_halfwidth_ascii:
            out.append(0x80)
            out.append(0x20)
            continue
        if use_halfwidth_ascii and 0x21 <= ord(ch) <= 0x7E:
            code = 0x8000 | ord(ch)
            out.append((code >> 8) & 0xFF)
            out.append(code & 0xFF)
            continue
        if ch in CHAR_TO_GLYPH_FW:
            code = CHAR_TO_GLYPH_FW[ch]
            out.append((code >> 8) & 0xFF)
            out.append(code & 0xFF)
            continue
        # Fallback for unmapped characters: question mark
        out.append(0x80 if use_halfwidth_ascii else 0x82)
        out.append(0x3F if use_halfwidth_ascii else 0x02)
    return bytes(out)
